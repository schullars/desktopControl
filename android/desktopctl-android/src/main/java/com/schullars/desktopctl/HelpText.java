package com.schullars.desktopctl;

final class HelpText {
    private HelpText() {
    }

    static String create(String version, String screenshotDirectory) {
        return "desktopctl " + version + " - Android automation command module\n"
                + "\n"
                + "Usage:\n"
                + "  desktopctl <command> [arguments]\n"
                + "\n"
                + "General options:\n"
                + "  -H, -h, --help, help\n"
                + "      Show this complete help text without starting a session.\n"
                + "  --version, version\n"
                + "      Show the module version after a session has started.\n"
                + "\n"
                + "Session lifecycle:\n"
                + "  desktopctl session start\n"
                + "  desktopctl session start --keep-alive\n"
                + "  desktopctl session stop\n"
                + "      Every non-help command requires a started session. A normal session stops after\n"
                + "      three minutes without a DesktopCTL command. RustDesk disconnection and process\n"
                + "      shutdown also remove the green activity indicator.\n"
                + "\n"
                + "Pointer and touch translation:\n"
                + "  desktopctl mouse move X Y\n"
                + "  desktopctl mouse move-relative DX DY\n"
                + "  desktopctl mouse click left [COUNT]\n"
                + "  desktopctl mouse down left\n"
                + "  desktopctl mouse up left\n"
                + "  desktopctl mouse wheel DELTA [vertical|horizontal]\n"
                + "      Android translates pointer commands into accessibility touch gestures. The green\n"
                + "      pointer is visual feedback; it is not a hardware mouse device. Screenshot pixels and\n"
                + "      absolute pointer commands use the same current display coordinate space.\n"
                + "\n"
                + "Keyboard input:\n"
                + "  desktopctl keyboard press KEY\n"
                + "  desktopctl keyboard down KEY\n"
                + "  desktopctl keyboard up KEY\n"
                + "  desktopctl keyboard hotkey KEY [KEY...]\n"
                + "  desktopctl keyboard type TEXT\n"
                + "  desktopctl keyboard type-unicode TEXT\n"
                + "      Text is committed as Unicode through the active Android input connection. Literal\n"
                + "      symbols such as @ and # must be passed as text, not reconstructed as Shift chords.\n"
                + "      type-physical is unavailable because stock Android accessibility does not expose a\n"
                + "      portable physical scan-code injection interface.\n"
                + "\n"
                + "Screenshots:\n"
                + "  desktopctl screenshot\n"
                + "  desktopctl screenshot full [OUTPUT.jpg]\n"
                + "      Capture the full RustDesk MediaProjection frame. The default is a timestamped\n"
                + "      quality-95 JPG. BMP remains available for lossless pixels. Region and window capture\n"
                + "      are not supported by the Android host.\n"
                + "      Output directory: " + screenshotDirectory + "\n"
                + "      The JSON response contains the path, image count, cleanup recommendation, width,\n"
                + "      height, scale, and rotation. More than 50 images triggers an English cleanup message.\n"
                + "\n"
                + "Applications:\n"
                + "  desktopctl app list\n"
                + "  desktopctl app open PACKAGE_OR_EXACT_NAME\n"
                + "      Application IDs are Android package names. Launching requires a launcher activity.\n"
                + "\n"
                + "Unsupported desktop concepts:\n"
                + "  Android does not expose Windows-style global window activation, hidden window bounds, or\n"
                + "  arbitrary application-window capture. window commands return an explicit error.\n"
                + "\n"
                + "RustDesk requirements:\n"
                + "  Start RustDesk screen capture and enable RustDesk Input accessibility before session start.\n"
                + "  The embedded command module reuses those services and does not request a second projection.\n"
                + "\n"
                + "Examples:\n"
                + "  desktopctl session start\n"
                + "  desktopctl screenshot\n"
                + "  desktopctl mouse move 540 1200\n"
                + "  desktopctl mouse click left\n"
                + "  desktopctl keyboard type \"admin@123#\"\n"
                + "  desktopctl app list\n"
                + "  desktopctl app open com.android.chrome\n"
                + "  desktopctl session stop\n"
                + "\n"
                + "Exit codes:\n"
                + "  0  Success\n"
                + "  2  Invalid command or arguments\n"
                + "  3  Missing session, unavailable permission, or platform operation failure\n";
    }
}
